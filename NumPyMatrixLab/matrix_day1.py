
import numpy as np

# ============================
# 实验 1：创建矩阵
# ============================

A = np.array([
    [1, 2],
    [3, 4]
])

B = np.array([
    [5, 6],
    [7, 8]
])

print("===== 实验1：创建矩阵 =====")
print("矩阵 A：")
print(A)

print("矩阵 B：")
print(B)

print("A 的尺寸：", A.shape)
print("B 的尺寸：", B.shape)


# ============================
# 实验 2：矩阵乘法
# ============================

C = A @ B

print("\n===== 实验2：矩阵乘法 =====")
print("A @ B =")
print(C)


# ============================
# 实验 3：逐元素乘法
# ============================

D = A * B

print("\n===== 实验3：逐元素乘法 =====")
print("A * B =")
print(D)


# ============================
# 实验 4：矩阵乘法顺序
# ============================

E = B @ A

print("\n===== 实验4：交换乘法顺序 =====")
print("B @ A =")
print(E)

print("A @ B 与 B @ A 是否相等：")
print(np.array_equal(C, E))


# ============================
# 实验 5：矩阵尺寸匹配
# ============================

F = np.array([
    [1, 2, 3],
    [4, 5, 6]
])

G = np.array([
    [1, 2],
    [3, 4],
    [5, 6]
])

H = F @ G

print("\n===== 实验5：矩阵尺寸 =====")
print("F 的尺寸：", F.shape)
print("G 的尺寸：", G.shape)
print("F @ G 的尺寸：", H.shape)
print("F @ G =")
print(H)
